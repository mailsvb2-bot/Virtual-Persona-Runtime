"""Branch integration inventory must preserve exact Git filenames."""
from __future__ import annotations

import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest


AUDIT = Path(__file__).resolve().parents[2] / "scripts/audit_branch_diffs.py"


@unittest.skipIf(os.name == "nt", "Windows cannot represent LF in filenames")
class BranchInventoryFilenameTests(unittest.TestCase):
    def test_unicode_tab_and_newline_paths_are_not_git_quoted(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)

            def git(*args: str) -> None:
                subprocess.run(
                    ["git", *args], cwd=root, check=True,
                    stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                )

            def add_file(name: str) -> None:
                (root / name).write_text("content\n", encoding="utf-8")

            git("init", "-q")
            git("config", "user.name", "VPR Test")
            git("config", "user.email", "vpr-test@example.invalid")
            add_file("base.py")
            git("add", ".")
            git("commit", "-qm", "base")
            git("branch", "-M", "main")
            git("checkout", "-qb", "feature")
            integrated = ["café.py", "tab\tname.py", "tail space .py"]
            absent = "newline\nname.py"
            for name in [*integrated, absent]:
                add_file(name)
            git("add", ".")
            git("commit", "-qm", "feature paths")
            git("update-ref", "refs/remotes/origin/feature", "HEAD")
            git("checkout", "-q", "main")
            for name in integrated:
                add_file(name)
            git("add", ".")
            git("commit", "-qm", "integrated paths")
            git("update-ref", "refs/remotes/origin/main", "HEAD")

            output = root / "branch-audit"
            subprocess.run(
                [sys.executable, str(AUDIT), "--out", str(output)],
                cwd=root, check=True, capture_output=True, text=True,
            )
            summary = json.loads((output / "summary.json").read_text(encoding="utf-8"))
            self.assertEqual(len(summary["branches"]), 1)
            self.assertEqual(summary["branches"][0]["name"], "feature")
            self.assertEqual(
                summary["branches"][0]["introduced_paths_missing_from_main"],
                [absent],
            )

            # The block-first output is generated by this same canonical
            # inventory and retains exact, potentially tricky Git filenames.
            block_report = json.loads(
                (output / "functional-blocks.json").read_text(encoding="utf-8")
            )
            self.assertEqual(block_report["main_sha"], summary["main_sha"])
            entries = block_report["blocks"]["other-integration"]
            self.assertEqual(len(entries), 1)
            self.assertEqual(entries[0]["absent_from_main"], [absent])
            self.assertEqual(entries[0]["identical_to_main"], integrated)
            self.assertTrue(entries[0]["requires_manual_review"])
            self.assertEqual(
                summary["branches"][0]["functional_blocks"]["other-integration"]
                    ["absent_from_main"],
                [absent],
            )

    @unittest.skipIf(os.name == "nt", "Git executable bits differ on Windows")
    def test_renames_keep_source_deletions_and_mode_changes_are_not_identical(self):
        import importlib.util
        spec = importlib.util.spec_from_file_location("branch_audit", AUDIT)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            def git(*args: str) -> None:
                subprocess.run(["git", *args], cwd=root, check=True,
                               stdout=subprocess.PIPE, stderr=subprocess.PIPE)
            git("init", "-q")
            git("config", "user.name", "VPR Test")
            git("config", "user.email", "vpr-test@example.invalid")
            (root / "old.py").write_text("same\n")
            (root / "script.py").write_text("script\n")
            git("add", ".")
            git("commit", "-qm", "base")
            git("branch", "-M", "main")
            git("checkout", "-qb", "feature")
            git("mv", "old.py", "new.py")
            git("update-index", "--chmod=+x", "script.py")
            git("commit", "-qm", "rename and change mode")
            git("reset", "--hard", "-q")
            git("update-ref", "refs/remotes/origin/feature", "HEAD")
            git("checkout", "-q", "main")
            (root / "new.py").write_text("same\n")
            git("add", "new.py")
            git("commit", "-qm", "main also adds destination")
            git("update-ref", "refs/remotes/origin/main", "HEAD")
            before = Path.cwd()
            try:
                os.chdir(root)
                base = module.git("merge-base", "origin/main", "origin/feature")
                result = module.branch_functional_blocks(base, "origin/feature")
            finally:
                os.chdir(before)
            paths = result["other-integration"]
            self.assertIn("old.py", paths["introduced_paths"])
            self.assertIn("new.py", paths["identical_to_main"])
            self.assertIn("old.py", paths["different_from_main"])
            self.assertIn("script.py", paths["different_from_main"])

    def test_functional_blocks_keep_runtime_and_workers_separate(self):
        import importlib.util
        spec = importlib.util.spec_from_file_location("branch_audit", AUDIT)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        self.assertEqual(
            module.functional_block("scripts/rt1_media_worker_http.py"),
            "rt1-media-worker",
        )
        self.assertEqual(
            module.functional_block("crates/vpr-owner-lab/src/rt1_visitor_conversation.rs"),
            "rt1-owner-visitor",
        )
        self.assertEqual(
            module.functional_block("crates/vpr-owner-lab/src/state/voice_delivery.rs"),
            "rt0-voice-and-playback",
        )
        self.assertEqual(
            module.functional_block("crates/vpr-provider-did-agent-streams/src/echo.rs"),
            "providers-and-runtime",
        )


if __name__ == "__main__":
    unittest.main()
